def briefing(mode, control_mode):
    if mode not in TITLES or control_mode not in ('body','gamepad'):
        raise ValueError('Unknown experience or control mode')
    if control_mode=='gamepad':
        lines=('\n'.join(GAMEPAD_HELP[mode]), *RULES[mode], '\n'.join(COMMON_GAMEPAD_HELP))
        message='方向键选择，A 确认，B 返回。看完说明后选择“开始”。'
    else:
        lines=(*BODY[mode], *RULES[mode])
        message='右手停留 2 秒确认。游戏中右臂在身体侧面转两圈，可暂停并查看说明。'
    return dict(title=TITLES[mode]+' · 开始前', lines=lines, message=message)
