"""Offline, reproducible ETC1 mip chain. Requires Pillow and C++17; no runtime dependency."""
import argparse,hashlib,json,os,subprocess
from pathlib import Path
from PIL import Image

def main():
 p=argparse.ArgumentParser();p.add_argument('--atlas',type=Path,required=True);p.add_argument('--base-pkm',type=Path,required=True)
 p.add_argument('--output',type=Path,required=True);p.add_argument('--work-dir',type=Path,required=True);p.add_argument('--compiler',required=True);a=p.parse_args()
 root=Path(__file__).resolve().parent;a.work_dir.mkdir(parents=True,exist_ok=False)
 env=dict(os.environ,TEMP=str(a.work_dir),TMP=str(a.work_dir),PYTHONDONTWRITEBYTECODE='1')
 sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
 source=Image.open(a.atlas).convert('RGBA');assert source.size==(1024,1024) and source.getextrema()[3]==(255,255)
 provenance=json.loads((root/'provenance.json').read_text(encoding='utf8'))
 assert sha(a.atlas)==provenance['source_png_sha256'] and sha(a.base_pkm)==provenance['base_pkm_sha256']
 for name,h in provenance['files'].items():assert sha(root/name)==h,name
 exe=a.work_dir/('codec.exe' if os.name=='nt' else 'codec')
 sources=[root/'codec_cli.cpp',root/'rg_etc1.cpp'];subprocess.run([a.compiler,'-std=c++17','-O2','-mstackrealign',*map(str,sources),'-o',str(exe)],env=env,capture_output=True,check=True)
 rows=[];all_data=bytearray()
 for level in range(1,11):
  size=1024>>level
  if size>=4:
   tile=size//4;image=Image.new('RGBA',(size,size))
   for y in range(4):
    for x in range(4):
     sub=source.crop((x*256,y*256,(x+1)*256,(y+1)*256)).resize((tile,tile),Image.Resampling.BOX)
     image.paste(sub,(x*tile,y*tile))
  else:image=source.resize((size,size),Image.Resampling.BOX)
  raw=a.work_dir/f'level-{level}.rgba';raw.write_bytes(image.tobytes());encoded=a.work_dir/f'level-{level}.etc1'
  run=subprocess.run([str(exe),str(raw),str(size),str(size),str(encoded)],env=env,capture_output=True,text=True,check=True)
  stats=json.loads(run.stdout);data=encoded.read_bytes();assert len(data)==((size+3)//4)**2*8 and stats['invalid']==0
  image.save(a.work_dir/f'level-{level}.png')
  rows.append(dict(level=level,width=size,height=size,offset=len(all_data),bytes=len(data),sha256=sha(encoded),**{k:v for k,v in stats.items() if k!='bytes'}));all_data.extend(data)
 lines=['#ifndef RUNNER_MATERIAL_MIPS_H','#define RUNNER_MATERIAL_MIPS_H','// Generated by runner/material_source/build_material_mips.py. Original base atlas is unchanged.','namespace runner_material_mips {',
  'static const char base_sha256[]="'+sha(a.base_pkm)+'";', 'static const char source_png_sha256[]="'+sha(a.atlas)+'";', 'struct Level {int width,height,offset,bytes;};','static const unsigned char data[]={']
 for i in range(0,len(all_data),24):lines.append(','.join(str(x) for x in all_data[i:i+24])+',')
 lines+=['};','static const Level levels[]={']+['{%d,%d,%d,%d},'%(r['width'],r['height'],r['offset'],r['bytes']) for r in rows]+['};','static const int level_count=sizeof(levels)/sizeof(levels[0]);','}','#endif','']
 a.output.parent.mkdir(parents=True,exist_ok=True);a.output.write_text('\n'.join(lines),encoding='utf8',newline='\n')
 report=dict(passed=True,source_png_sha256=sha(a.atlas),base_pkm_sha256=sha(a.base_pkm),header_sha256=sha(a.output),additional_gpu_bytes=len(all_data),levels=rows,
  tool_sources={q.name:sha(q) for q in [Path(__file__),root/'codec_cli.cpp',root/'rg_etc1.h',root/'rg_etc1.cpp',root/'provenance.json']},
  note='Ten pre-encoded ETC1 levels; per-tile box filtering for 512 through4, whole-atlas leaf2/1. No runtime encoding and no base image changes.')
 (a.work_dir/'build-report.json').write_text(json.dumps(report,indent=2),encoding='utf8');print(json.dumps(dict(passed=True,header_sha256=report['header_sha256'],additional_gpu_bytes=len(all_data))))
if __name__=='__main__':main()
